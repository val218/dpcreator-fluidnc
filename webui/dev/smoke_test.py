#!/usr/bin/env python3
"""Headless smoke test against dev/mock_fluidnc.py: loads the UI, exercises
DRO, jog, file preview, run, console errors, and saves screenshots."""
import sys
import pathlib
from playwright.sync_api import sync_playwright

OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/webui-shots")
OUT.mkdir(parents=True, exist_ok=True)
URL = "http://127.0.0.1:8080/"
errors = []


def check(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond:
        errors.append(msg)


with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"])
    page = b.new_page(viewport={"width": 1600, "height": 900})
    page.on("console", lambda m: m.type == "error" and errors.append("console: " + m.text))
    page.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
    page.goto(URL)
    page.wait_for_function("document.querySelector('#conn').textContent === 'online'", timeout=8000)
    check(True, "connected")
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=5000)
    check(page.inner_text("#ax-X .wpos") == "100.000", "DRO X shows WPos = MPos - WCO (100.000)")

    # file list + preview
    page.wait_for_selector("#file-list li:has-text('job1.nc')", timeout=5000)
    page.click("#file-list li:has-text('job1.nc')")
    page.click("#preview")
    page.wait_for_function("document.querySelector('#viewer-file').textContent === 'job1.nc'", timeout=8000)
    info = page.inner_text("#viewer-info")
    check("×" in info and "mm" in info, f"preview info: {info}")
    page.screenshot(path=str(OUT / "desktop-preview.png"))

    # step jog X+ 10
    page.click("#step button[data-step='10']")
    page.click("button[data-jog='X1']")
    page.wait_for_function("document.querySelector('#ax-X .wpos').textContent === '110.000'", timeout=6000)
    check(True, "step jog moved X by 10")

    # zero X
    page.click("#ax-X .z0")
    page.wait_for_function("document.querySelector('#ax-X .wpos').textContent === '0.000'", timeout=4000)
    check(True, "zero X sets WPos 0")

    # console error
    page.fill("#cmd", "bad")
    page.press("#cmd", "Enter")
    page.wait_for_function("document.querySelector('#log').textContent.includes('Unsupported G-code')", timeout=4000)
    check(True, "error code described in console")

    # upload G-code to SD -> pendant .viz is built, sidecar hidden from list
    page.set_input_files("#upload", files=[{"name": "upl.nc", "mimeType": "text/plain",
                                            "buffer": b"G0 X0 Y0\nG1 X10 Y10 F500\nG1 X0\n"}])
    page.wait_for_selector("#log :text('VizAutoReady:/sd/upl.nc.viz')", timeout=6000)
    check(True, "upload to SD -> firmware builds .viz (VizAutoReady)")
    page.wait_for_selector("#file-list li:has-text('upl.nc')", timeout=4000)
    names = page.eval_on_selector_all("#file-list .fname", "els => els.map(e => e.textContent)")
    check("upl.nc.viz" not in names, f".viz sidecar hidden from list: {names}")
    check(page.evaluate("document.querySelector('.brand-logo').naturalWidth > 0"), "logo image renders")
    check(page.inner_text("#pendant") == "Pendant" and page.is_visible("#pendant"), "pendant badge shows connected")
    page.evaluate("fetch('/mock/pendant?state=disconnected')")
    page.wait_for_function("document.querySelector('#pendant').textContent === 'Pendant offline'", timeout=3000)
    check(True, "pendant badge follows disconnect message")
    page.screenshot(path=str(OUT / "desktop-pendant-offline.png"), clip={"x": 0, "y": 0, "width": 1600, "height": 70})
    page.evaluate("fetch('/mock/pendant?state=connected')")
    page.wait_for_function("document.querySelector('#pendant').textContent === 'Pendant'", timeout=3000)
    page.screenshot(path=str(OUT / "desktop-viz.png"))
    page.wait_for_selector("#crash:not([hidden])", timeout=3000)
    check("PC=0x42001234" in page.inner_text("#crash-text"), "crash banner shows the backtrace ($Crash)")
    check(not page.is_visible("#uiold"), "no page/firmware mismatch warning for a matching build")
    page.evaluate("fetch('/mock/ver?sha=abcdef1')")
    page.wait_for_selector("#uiold:not([hidden])", timeout=3000)
    check("abcdef1" in page.inner_text("#uiold-text"), "older page than firmware: warning says to flash the filesystem")
    page.click("#uiold-hide")
    page.click("#crash-hide")
    # monitor strip present with one row per axis
    check(page.locator(".mon-axis").count() == 4, "axis monitor has 4 axes")

    # PC drive script download has the board IP filled in
    with page.expect_download() as dl:
        page.click("#pc-drive")
    path = dl.value.path()
    body = open(path, "rb").read().decode()
    check('set "DEFAULT_IP=127.0.0.1"' in body and 'set "ASK_IP=0"' in body and "\r\n" in body,
          "PC drive script: IP filled in, no prompt, CRLF")

    # manual pendant .viz with confirmation
    page.once("dialog", lambda d: d.accept())
    page.click("#file-list li:has-text('job1.nc')")
    page.click("#make-viz")
    page.wait_for_selector("#log :text('VizAutoReady:/sd/job1.nc.viz')", timeout=6000)
    check(True, "Pendant .viz button (confirmed) builds job1.nc.viz")
    page.wait_for_selector("#file-list li:has-text('job1.nc') .vizdot.viz-ok", timeout=3000)
    check("viz-ok" in page.get_attribute("#make-viz", "class"), ".viz state: green dot + green button once built")
    page.click("#refresh")
    page.wait_for_selector("#file-list li:has-text('job1.nc') .vizdot.viz-ok", timeout=3000)
    check(True, ".viz state survives a list refresh (from the card listing)")

    # job started elsewhere while another file is shown -> 2D .viz outline, full path when stopped
    page.click("#file-list li:has-text('upl.nc')")
    page.click("#preview")
    page.wait_for_function("document.querySelector('#viewer-file').textContent === 'upl.nc'", timeout=6000)
    page.set_input_files("#upload", files=[{"name": "big.nc", "mimeType": "text/plain",
                                            "buffer": b"G0 X0 Y0\nG1 Z-1 F300\nG1 X40 Y0 F800\nG1 X40 Y30\nG1 X0 Y30\nG1 X0 Y0\n"}])
    page.wait_for_selector("#log :text('VizAutoReady:/sd/big.nc.viz')", timeout=6000)
    page.fill("#cmd", "$SD/Run=/big.nc")
    page.press("#cmd", "Enter")
    page.wait_for_function("document.querySelector('#viewer-file').textContent.includes('big.nc · preview')", timeout=6000)
    check(True, "running job from elsewhere shows the .viz preview while moving")
    page.screenshot(path=str(OUT / "desktop-job-viz.png"))
    page.click("button[data-cmd='stop']")
    page.wait_for_function("document.querySelector('#viewer-file').textContent === 'big.nc'", timeout=8000)
    check(True, "full 3D path loads once the machine stops")
    page.wait_for_selector("#recovery:not([hidden])", timeout=4000)
    check("big.nc" in page.inner_text("#rec-file"), "stopped job offered for recovery")
    page.wait_for_selector("#rec-ready:not([hidden])", timeout=3000)
    check(page.is_disabled("#rec-go") and not page.is_disabled("#rec-unlock"),
          "in alarm: Resume disabled, Unlock offered in the recovery card")
    page.click("#rec-unlock")
    page.wait_for_selector("#rec-ready[hidden]", state="attached", timeout=3000)
    check(True, "Unlock from the recovery card clears the alarm")
    page.click("#rec-later")
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=5000)
    page.wait_for_timeout(500)
    page.click("#file-list li:has-text('job1.nc')")

    # prepare -> shown on the pendant -> run from the bar
    page.on("dialog", lambda d: d.accept())
    check(page.inner_text("#run").strip() == "Prepare", "SD G-code file: button says Prepare")
    page.click("#run")
    page.wait_for_selector("#prepared:not([hidden]) .prep-state.loading", timeout=3000)
    page.wait_for_selector("#prepared .prep-state.ready", timeout=4000)
    check("job1.nc" in page.inner_text("#prep-name"), "prepared bar: job1.nc shown on the pendant")
    page.screenshot(path=str(OUT / "desktop-prepared.png"))
    page.click("#prep-cancel")
    page.wait_for_selector("#prepared[hidden]", state="attached", timeout=3000)
    page.wait_for_function("document.querySelector('#viewer-file').textContent === 'No file loaded'", timeout=3000)
    check(True, "Cancel clears the prepared job and its preview")
    page.click("#run")
    page.wait_for_selector("#prepared .prep-state.ready", timeout=4000)
    page.click("#prep-run")
    page.wait_for_function("!document.querySelector('#job').hidden", timeout=6000)
    page.wait_for_selector("#prepared[hidden]", state="attached", timeout=3000)
    check("job1.nc" in page.inner_text("#viewer-file"), "Run from the bar starts the job, clears the bar, keeps the preview")
    page.wait_for_timeout(2500)
    check("job1.nc" in page.inner_text("#job"), "job progress shown: " + page.inner_text("#job"))
    check(page.inner_text("#state") == "Run", "state Run during job")
    # live Z adjust while the job runs
    check(not page.is_disabled("[data-zadj='+0.1']"), "Z adjust buttons enabled while the job runs")
    check(page.is_visible("#jobzadj"), "Z adjust bar shown above the 3D view while the job runs")
    page.click("#jobzadj [data-zadj='+0.1']")
    page.click("#jobzadj [data-zadj='-0.01']")
    page.wait_for_function("document.querySelector('#zadj').textContent === '+0.090'", timeout=3000)
    page.wait_for_selector("#zadj-note.active", timeout=3000)
    check(page.inner_text("#jobzadj .zadj-val") == "+0.090", "job bar shows the offset too")
    page.screenshot(path=str(OUT / "desktop-zadjust-running.png"))
    check("shallower" in page.inner_text("#zadj-note"), "Z adjust +0.090 active: " + page.inner_text("#zadj-note"))
    moving = page.evaluate("[...document.querySelectorAll('.mon-axis .led')].some(l => l.classList.contains('led-move'))")
    check(moving, "axis monitor shows moving axes during job")
    page.screenshot(path=str(OUT / "desktop-running.png"))
    page.click("button[data-cmd='hold']")
    page.wait_for_function("document.querySelector('#state').textContent.startsWith('Hold')", timeout=3000)
    check(True, "feed hold works")
    # handwheel rewind in Hold
    page.wait_for_selector("#rewind:not([hidden])", timeout=3000)
    page.click("#rw-start")
    page.wait_for_selector("#rw-ctl:not([hidden])", timeout=3000)
    page.click("[data-rw='-1']")
    page.click("[data-rw='-1']")
    page.click("[data-rw='0.1']")
    page.click("[data-rwz='+0.1']")
    page.wait_for_function("document.querySelector('#rw-pos').textContent === '1.90 mm'", timeout=3000)
    page.wait_for_function("document.querySelector('#rw-z').textContent === '+0.100'", timeout=3000)
    check(True, "rewind: 1.9 mm back, Z +0.1 shown")
    page.screenshot(path=str(OUT / "desktop-rewind.png"))
    page.click("#rw-go")
    page.wait_for_function("document.querySelector('#state').textContent === 'Run'", timeout=4000)
    page.wait_for_selector("#rw-ctl[hidden]", state="attached", timeout=3000)
    check(True, "Continue re-cuts and resumes the job")
    page.click("button[data-cmd='hold']")
    page.wait_for_function("document.querySelector('#state').textContent.startsWith('Hold')", timeout=3000)
    page.click("button[data-cmd='stop']")
    page.wait_for_function("document.querySelector('#state').textContent === 'Alarm'", timeout=4000)
    check(True, "stop while cutting -> Alarm")
    page.wait_for_selector("#rec-ready:not([hidden])", timeout=3000)
    page.click("#rec-unlock")
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=4000)
    page.wait_for_selector("#zadj-end:not([hidden])", timeout=3000)
    check("+0.190" in page.inner_text("#zadj-end"), "job ended with Z adjust +0.09 + rewind +0.1: offer to move the work zero")
    check(page.is_disabled("[data-zadj='+0.1']"), "Z adjust buttons disabled without a job")
    check(not page.is_visible("#jobzadj"), "Z adjust bar hidden without a job")
    wz = page.inner_text("#ax-Z .wpos")
    page.screenshot(path=str(OUT / "desktop-zadjust-end.png"))
    page.click("#zadj-apply")
    page.wait_for_selector("#zadj-end[hidden]", state="attached", timeout=3000)
    page.wait_for_function(f"document.querySelector('#ax-Z .wpos').textContent !== '{wz}'", timeout=3000)
    check(True, f"Apply moved the work Z zero (Z {wz} -> {page.inner_text('#ax-Z .wpos')})")

    # job recovery: the board keeps the stopped job; the panel offers restart points
    page.wait_for_selector("#recovery:not([hidden])", timeout=4000)
    page.wait_for_function("document.querySelector('#rec-choices').textContent.includes('line 32')", timeout=4000)
    check("job1.nc" in page.inner_text("#rec-file") and "line 45" in page.inner_text("#rec-why"),
          "recovery panel: file and stop line shown")
    check(page.inner_text("#rec-go").strip() == "▶ Resume from line 32", "last retract preselected ($Job/Points)")
    page.wait_for_function("document.querySelector('#rec-text .here') !== null", timeout=4000)
    check("G0 X10 Y10" in page.inner_text("#rec-text .here") or page.inner_text("#rec-text .here").strip().startswith("32"),
          "G-code around the restart line shown: " + page.inner_text("#rec-text .here"))
    page.fill("#rec-choices input[type=number]", "40")
    check(page.inner_text("#rec-go").strip() == "▶ Resume from line 40", "custom line")
    page.screenshot(path=str(OUT / "desktop-recovery.png"))
    page.click("#rec-later")
    check(not page.is_visible("#rec-body") and page.is_visible("#rec-show"), "Later collapses the panel")
    page.click("#rec-show")
    page.click("#rec-choices .rec-choice >> nth=0")
    page.click("#rec-go")
    page.wait_for_selector("#recovery[hidden]", state="attached", timeout=4000)
    page.wait_for_function("!document.querySelector('#job').hidden", timeout=6000)
    check(True, "Resume continues the job and closes the panel")
    page.click("button[data-cmd='stop']")
    page.wait_for_selector("#recovery:not([hidden])", timeout=4000)
    page.click("#rec-discard")
    page.wait_for_selector("#recovery[hidden]", state="attached", timeout=4000)
    check(True, "Discard forgets the interrupted job")

    # macros: starter set on the board, run, edit in the dialog
    if page.inner_text("#state") == "Alarm":
        page.click("button[data-cmd='unlock']")
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=5000)
    page.wait_for_function("document.querySelectorAll('#macro-grid .mbtn').length >= 3", timeout=4000)
    check(True, "macros panel lists the board's macros")
    page.click("#macros-edit")
    page.wait_for_function("document.querySelectorAll('#mdlg-list li').length >= 3", timeout=4000)
    page.wait_for_function("document.querySelector('#mdlg-code').value.includes('G53')", timeout=3000)
    check(True, "editor loads the list and the first macro")
    page.click("#mdlg-new")
    page.fill("#mdlg-name", "Test probe")
    page.fill("#mdlg-code", "G91\nG0 Z1\nG90\n")
    page.click("#mdlg-save")
    page.wait_for_function("[...document.querySelectorAll('#macro-grid .mbtn')].some(b => b.textContent === 'Test probe')", timeout=4000)
    check(True, "new macro saved to the SD card and shown in the panel")
    page.screenshot(path=str(OUT / "desktop-macros.png"))
    page.click("#mdlg-close")
    page.click("#macro-grid .mbtn:has-text('Park')")
    page.wait_for_function("!document.querySelector('#job').hidden", timeout=4000)
    check(True, "macro runs as a job")
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=8000)

    # work offsets table
    page.click("#offsets-open")
    page.wait_for_function("document.querySelectorAll('#offsets tr').length === 7 && document.querySelector('#offsets input').value !== ''", timeout=4000)
    g54x = page.input_value("#offsets tr:nth-child(2) td:nth-child(2) input")
    check(g54x.replace(".", "").replace("-", "").isdigit(), "offsets table: G54 X = " + g54x)
    page.fill("#offsets tr:nth-child(3) td:nth-child(2) input", "12.5")
    page.press("#offsets tr:nth-child(3) td:nth-child(2) input", "Enter")
    page.wait_for_function("document.querySelector('#offsets tr:nth-child(3) td:nth-child(2) input').value === '12.500'", timeout=4000)
    check(True, "edit G55 X via G10 L2")
    page.screenshot(path=str(OUT / "desktop-offsets.png"))
    page.click("#offsets-close")

    # tools: table, setter info from $/atc_manual, M6 with the install prompt
    page.wait_for_function("document.querySelector('#state').textContent === 'Idle'", timeout=8000)
    page.click("#tools-open")
    page.wait_for_selector("#tools-setter.ok", timeout=4000)
    check("5.000" in page.inner_text("#tools-setter"), "tool setter read from $/atc_manual: " + page.inner_text("#tools-setter"))
    page.click("#tools-add")
    page.fill("#tools-table tr:nth-child(3) input.tname", "6 mm flat end mill")
    page.click("#tools-save")
    page.wait_for_function("document.querySelector('#tools-status').textContent.includes('Saved')", timeout=4000)
    check(True, "tool list saved on the SD card")
    page.screenshot(path=str(OUT / "desktop-tools.png"))
    page.click("#tools-table tr:nth-child(3) button:has-text('Change')")
    page.wait_for_selector("#toolprompt:not([hidden])", timeout=4000)
    check("T2" in page.inner_text("#toolprompt-text"), "M6 T2: install prompt shown: " + page.inner_text("#toolprompt-text"))
    page.click("#tools-close")
    page.click("#toolprompt-resume")
    page.wait_for_selector("#toolprompt[hidden]", state="attached", timeout=3000)
    check(True, "Resume from the install prompt")

    # tablet + phone layouts
    page.set_viewport_size({"width": 1024, "height": 768})
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT / "tablet.png"), full_page=True)
    page.set_viewport_size({"width": 390, "height": 844})
    page.wait_for_timeout(400)
    page.screenshot(path=str(OUT / "phone-control.png"))
    page.click("#tabs button[data-view='viewer']")
    page.wait_for_timeout(500)
    page.screenshot(path=str(OUT / "phone-viewer.png"))
    overflow = page.evaluate("document.documentElement.scrollWidth > window.innerWidth")
    check(not overflow, "no horizontal overflow on phone")
    b.close()

print("\nERRORS:" if errors else "\nALL OK")
for e in errors:
    print(" -", e)
sys.exit(1 if errors else 0)
